import React from 'react';
import { render, screen, fireEvent, waitFor } from '@testing-library/react';
import CrearPuesto from '../components/ComponentesPuesto/CrearPuesto';
import { UserContext } from '../components/ComponentesGenerales/UserContext';
import { toast } from 'react-toastify';
const mockNavigate = jest.fn();
jest.mock('react-router-dom', () => ({ useNavigate: () => mockNavigate, Link: ({ children, to }) => <a href={to}>{children}</a> }));
jest.mock('../components/ComponentesGenerales/PageLayout', () => ({ children }) => <div>{children}</div>);
jest.mock('../components/ComponentesGenerales/Footer', () => () => null);
jest.mock('../components/ComponentesGenerales/Utils/base64', () => ({ fileToBase64: (file, callback) => callback(`data:image/png;base64,${file.name}`) }));
jest.mock('react-toastify', () => ({ toast: { success: jest.fn(), error: jest.fn() } }));
const renderForm = () => render(<UserContext.Provider value={{ user: { consumidorId: 7 } }}><CrearPuesto /></UserContext.Provider>);
afterEach(() => { if (global.fetch.mockRestore) global.fetch.mockRestore(); jest.clearAllMocks(); });
test('missing AFIP documentation preserves existing validation', () => {
  const fetchMock = jest.spyOn(global, 'fetch');
  renderForm();
  fireEvent.click(screen.getByRole('button', { name: 'Registrar Carro de Comida' }));
  expect(toast.error).toHaveBeenCalledWith('Debe adjuntar la constancia de AFIP');
  expect(fetchMock).not.toHaveBeenCalled();
});
test('previews images and submits only once with the existing API payload', async () => {
  let resolve;
  const fetchMock = jest.spyOn(global, 'fetch').mockImplementation(() => new Promise((done) => { resolve = done; }));
  renderForm();
  fireEvent.change(screen.getByLabelText('Nombre Carro'), { target: { value: 'Cuarteto' } });
  fireEvent.change(screen.getByLabelText('Número de Carro'), { target: { value: '12' } });
  fireEvent.change(screen.getByLabelText('Teléfono'), { target: { value: '3511234567' } });
  fireEvent.change(screen.getByLabelText('Tipo de Negocio'), { target: { value: 'Pizzería' } });
  for (const label of ['Logo', 'Banner']) fireEvent.change(screen.getByLabelText(label), { target: { files: [new File(['img'], `${label}.png`, { type: 'image/png' })] } });
  fireEvent.change(screen.getByLabelText('Constancia de inscripción a AFIP'), { target: { files: [new File(['pdf'], 'afip.pdf', { type: 'application/pdf' })] } });
  expect(screen.getByAltText('Vista previa del logo')).toBeInTheDocument();
  expect(screen.getByAltText('Vista previa del banner')).toBeInTheDocument();
  const button = screen.getByRole('button', { name: 'Registrar Carro de Comida' });
  fireEvent.click(button); fireEvent.click(button);
  expect(fetchMock).toHaveBeenCalledTimes(1);
  expect(button).toBeDisabled();
  expect(JSON.parse(fetchMock.mock.calls[0][1].body)).toEqual(expect.objectContaining({ nombreCarro: 'Cuarteto', numeroCarro: '12', tipoNegocio: 'Pizzería', consumidorId: 7 }));
  resolve({ json: async () => ({ code: 200 }) });
  await waitFor(() => expect(mockNavigate).toHaveBeenCalledWith('/listado-puestos-encargado'));
});
